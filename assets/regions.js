const SET = new Set(REGIONS);
// 긴 이름을 먼저 봐야 "광주시"가 "광주"로 잘리지 않는다.
const SORTED = [...REGIONS].sort((a, b) => b.length - a.length);

// 행정 접미사가 붙은 정식 표기는 그대로 신뢰한다 — "가평군", "용인시", "성수동".
// 단 어미와 겹치지 않도록 앞 글자가 실제 지명일 때만 인정한다.
const FORMAL = /([가-힣]{2,5})(특별시|광역시|시|군|구|읍|면|동|리)(?![가-힣])/g;

export function findRegion(text) {
  if (!text) return '';
  for (const m of text.matchAll(FORMAL)) {
    if (SET.has(m[1]) || SET.has(m[1] + m[2])) return m[1] + m[2];
  }
  for (const r of SORTED) {
    // 앞뒤가 한글이면 다른 단어의 일부다 — "성수"가 "성수기"에 걸리지 않게.
    const i = text.indexOf(r);
    if (i < 0) continue;
    const before = text[i - 1], after = text[i + r.length];
    if (before && /[가-힣]/.test(before)) continue;
    if (after && /[가-힣]/.test(after) && !/(시|군|구|읍|면|동|리|역|쪽|근처|에서|에|의)/.test(after)) continue;
    return r;
  }
  return '';
}
